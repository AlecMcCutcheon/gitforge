#!/usr/bin/env node
/**
 * Write web/src/freenet/owner-constants.ts from built Hub WASM artefacts.
 *
 * Usage:
 *   node scripts/gen-forge-owner-constants.mjs <registry.wasm> <identity.wasm> \
 *     [--identity-code-b58 <b58>] [--vault <vault.wasm>] [--stars <stars.wasm>] \
 *     [--profile <profile.wasm>] [--repo <repo.wasm>]
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const require = createRequire(join(root, "web/package.json"));

const args = process.argv.slice(2);
let identityCodeB58 = null;
let vaultPath = null;
let starsPath = null;
let profilePath = null;
let repoPath = null;
let pagesPath = null;
let pagesCodeB58 = null;
const positional = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--identity-code-b58") {
    identityCodeB58 = args[++i];
  } else if (args[i] === "--vault") {
    vaultPath = args[++i];
  } else if (args[i] === "--stars") {
    starsPath = args[++i];
  } else if (args[i] === "--profile") {
    profilePath = args[++i];
  } else if (args[i] === "--repo") {
    repoPath = args[++i];
  } else if (args[i] === "--pages") {
    pagesPath = args[++i];
  } else if (args[i] === "--pages-code-b58") {
    pagesCodeB58 = args[++i];
  } else {
    positional.push(args[i]);
  }
}

const registryPath = positional[0];
const identityPath = positional[1];
if (!registryPath || !identityPath) {
  console.error(
    "usage: gen-forge-owner-constants.mjs <registry.wasm> <identity.wasm> [--identity-code-b58 <b58>] [--vault <vault.wasm>] [--stars <stars.wasm>] [--profile <profile.wasm>]",
  );
  process.exit(1);
}

const { blake3 } = require("@noble/hashes/blake3");
const bs58mod = require("bs58");
const bs58 = bs58mod.default ?? bs58mod;

function hashWasm(path) {
  const bytes = readFileSync(path);
  const digest = blake3(bytes);
  return {
    hex: Buffer.from(digest).toString("hex"),
    base58: bs58.encode(digest),
    bytes: Array.from(digest),
  };
}

const registry = hashWasm(registryPath);
let identityBytes;
let identityHex;
let identityB58;
if (identityCodeB58) {
  identityBytes = bs58.decode(identityCodeB58);
  if (identityBytes.length !== 32) {
    console.error("identity code hash must decode to 32 bytes");
    process.exit(1);
  }
  identityHex = Buffer.from(identityBytes).toString("hex");
  identityB58 = identityCodeB58;
} else {
  const identity = hashWasm(identityPath);
  identityBytes = identity.bytes;
  identityHex = identity.hex;
  identityB58 = identity.base58;
}

const vault = vaultPath ? hashWasm(vaultPath) : { base58: "" };
const stars = starsPath ? hashWasm(starsPath) : { base58: "" };
const profile = profilePath ? hashWasm(profilePath) : { base58: "" };
const repo = repoPath ? hashWasm(repoPath) : { base58: "" };

// Delegate key = blake3(code_hash_bytes) — microblogging Makefile.
const keyDigest = blake3(Uint8Array.from(identityBytes));
const keyBytes = Array.from(keyDigest);

const outDir = join(root, "web/src/freenet");
mkdirSync(outDir, { recursive: true });
const out = join(outDir, "owner-constants.ts");

const body = `/* AUTO-GENERATED by scripts/gen-forge-owner-constants.mjs — do not edit by hand */
/* registry: ${registryPath} */
/* identity wasm: ${identityPath} */
/* vault wasm: ${vaultPath || "(none)"} */
/* stars wasm: ${starsPath || "(none)"} */
/* profile wasm: ${profilePath || "(none)"} */
/* repo wasm: ${repoPath || "(none)"} */
/* identity code hash source: ${identityCodeB58 ? "fdev inspect (packaged)" : "blake3(wasm)"} */

/** UTF-8 parameters for the singleton ForgeRegistry instance. */
export const FORGE_REGISTRY_PARAMS_UTF8 = "gitforge-registry-v1";

/** BLAKE3 of hub_registry.wasm (base58). */
export const FORGE_REGISTRY_WASM_HASH_B58 = "${registry.base58}";

/** UTF-8 parameters prefix for GitForge vault (vault_id hex appended by SPA). */
export const FORGE_VAULT_PARAMS_PREFIX = "gitforge-vault-v1:";

/** BLAKE3 of hub_vault.wasm (base58). Empty until vault artefact is passed. */
export const FORGE_VAULT_WASM_HASH_B58 = "${vault.base58}";

/** UTF-8 parameters for the singleton GitForge stars instance. */
export const FORGE_STARS_PARAMS_UTF8 = "gitforge-stars-v1";

/** BLAKE3 of hub_stars.wasm (base58). Empty until stars artefact is passed. */
export const FORGE_STARS_WASM_HASH_B58 = "${stars.base58}";

/** UTF-8 parameters prefix for GitForge profile (fingerprint appended by SPA). */
export const FORGE_PROFILE_PARAMS_PREFIX = "gitforge-profile-v1:";

/** BLAKE3 of hub_profile.wasm (base58). Empty until profile artefact is passed. */
export const FORGE_PROFILE_WASM_HASH_B58 = "${profile.base58}";

/** UTF-8 parameters prefix for ForgeRepoMeta (repo_prefix appended by SPA). */
export const FORGE_REPO_PARAMS_PREFIX = "gitforge-repo-v1:";

/** BLAKE3 of hub_repo.wasm (base58). Empty until repo-meta artefact is passed. */
export const FORGE_REPO_WASM_HASH_B58 = "${repo.base58}";

/** Identity delegate key = blake3(code_hash) as byte array (32). */
export const FORGE_IDENTITY_KEY_BYTES: number[] = ${JSON.stringify(keyBytes)};

/** Identity delegate code hash as byte array (32). */
export const FORGE_IDENTITY_CODE_HASH_BYTES: number[] = ${JSON.stringify(Array.from(identityBytes))};

export function forgeOwnerContractsReady(): boolean {
  return (
    FORGE_REGISTRY_WASM_HASH_B58.length > 0 &&
    FORGE_IDENTITY_KEY_BYTES.length === 32 &&
    FORGE_IDENTITY_CODE_HASH_BYTES.length === 32
  );
}

export function forgeVaultReady(): boolean {
  return FORGE_VAULT_WASM_HASH_B58.length > 0;
}

export function forgeStarsReady(): boolean {
  return FORGE_STARS_WASM_HASH_B58.length > 0;
}

export function forgeProfileReady(): boolean {
  return FORGE_PROFILE_WASM_HASH_B58.length > 0;
}

export function forgeRepoReady(): boolean {
  return FORGE_REPO_WASM_HASH_B58.length > 0;
}
`;

writeFileSync(out, body);
console.log(`Wrote ${out}`);
console.log(`REGISTRY ${registry.base58}`);
console.log(`VAULT ${vault.base58 || "(empty)"}`);
console.log(`STARS ${stars.base58 || "(empty)"}`);
console.log(`PROFILE ${profile.base58 || "(empty)"}`);
console.log(`REPO ${repo.base58 || "(empty)"}`);
console.log(`IDENTITY code ${identityHex} (${identityB58})`);
console.log(`IDENTITY key  ${Buffer.from(keyDigest).toString("hex")}`);

// NEW CODE - TESTING: pages-delegate constants
const pagesOut = join(outDir, "pages-constants.ts");
let pagesKeyBytes = [];
let pagesCodeBytes = [];
let pagesCodeHex = "";
if (pagesPath || pagesCodeB58) {
  let codeBytes;
  if (pagesCodeB58) {
    codeBytes = bs58.decode(pagesCodeB58);
    if (codeBytes.length !== 32) {
      console.error("pages code hash must decode to 32 bytes");
      process.exit(1);
    }
  } else {
    codeBytes = Uint8Array.from(hashWasm(pagesPath).bytes);
  }
  pagesCodeBytes = Array.from(codeBytes);
  pagesCodeHex = Buffer.from(codeBytes).toString("hex");
  pagesKeyBytes = Array.from(blake3(Uint8Array.from(codeBytes)));
}
const pagesBody = `/* AUTO-GENERATED by scripts/gen-forge-owner-constants.mjs — do not edit by hand */
/* pages wasm: ${pagesPath || "(none)"} */
/* pages code hash source: ${pagesCodeB58 ? "fdev inspect (packaged)" : pagesPath ? "blake3(wasm)" : "empty"} */

/** Pages delegate key = blake3(code_hash) as byte array (32). Empty until built. */
export const FORGE_PAGES_KEY_BYTES: number[] = ${JSON.stringify(pagesKeyBytes)};

/** Pages delegate code hash as byte array (32). Empty until built. */
export const FORGE_PAGES_CODE_HASH_BYTES: number[] = ${JSON.stringify(pagesCodeBytes)};

export function forgePagesReady(): boolean {
  return (
    FORGE_PAGES_KEY_BYTES.length === 32 &&
    FORGE_PAGES_CODE_HASH_BYTES.length === 32
  );
}
`;
writeFileSync(pagesOut, pagesBody);
console.log(`Wrote ${pagesOut}`);
if (pagesCodeHex) {
  console.log(`PAGES code ${pagesCodeHex}`);
  console.log(`PAGES key  ${Buffer.from(pagesKeyBytes).toString("hex")}`);
}
