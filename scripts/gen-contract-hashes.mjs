#!/usr/bin/env node
/**
 * Generate web/src/freenet/constants.ts from freenet-git repo/pack contract WASM.
 * Prefer workspace contracts; fall back to freenet-git-0.1.24 crates.io unpack.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const require = createRequire(join(root, "web/package.json"));

let blake3;
let bs58;
try {
  blake3 = require("@noble/hashes/blake3").blake3;
  bs58 = require("bs58");
} catch {
  console.error(
    "Missing @noble/hashes / bs58 — run npm install in freenet-hub first.",
  );
  process.exit(1);
}

function findWasm(name) {
  const candidates = [
    join(
      root,
      "../freenet-git/crates/freenet-git/contracts",
      name,
    ),
    join(
      process.env.HOME || "",
      ".cargo/registry/src/index.crates.io-1949cf8c6b5b557f/freenet-git-0.1.24/contracts",
      name,
    ),
  ];
  for (const p of candidates) {
    if (existsSync(p)) return p;
  }
  throw new Error(`Cannot find ${name}. Build freenet-git contracts first.`);
}

function hashWasm(path) {
  const bytes = readFileSync(path);
  const digest = blake3(bytes);
  return {
    hex: Buffer.from(digest).toString("hex"),
    base58: bs58.default ? bs58.default.encode(digest) : bs58.encode(digest),
  };
}

const repoPath = findWasm("repo-contract.wasm");
const packPath = findWasm("pack-contract.wasm");
const repo = hashWasm(repoPath);
const pack = hashWasm(packPath);

const outDir = join(root, "web/src/freenet");
mkdirSync(outDir, { recursive: true });
const out = join(outDir, "constants.ts");

const body = `/* AUTO-GENERATED by scripts/gen-contract-hashes.mjs — do not edit by hand */
/* repo: ${repoPath} */
/* pack: ${packPath} */

/** BLAKE3 of freenet-git repo-contract.wasm (base58, 32 bytes decoded). */
export const REPO_WASM_HASH_B58 = "${repo.base58}";

/** BLAKE3 of freenet-git pack-contract.wasm (base58, 32 bytes decoded). */
export const PACK_WASM_HASH_B58 = "${pack.base58}";

/** Hex forms (debug / tests). */
export const REPO_WASM_HASH_HEX = "${repo.hex}";
export const PACK_WASM_HASH_HEX = "${pack.hex}";
`;

writeFileSync(out, body);
console.log(`Wrote ${out}`);
console.log(`REPO ${repo.base58}`);
console.log(`PACK ${pack.base58}`);
// silence unused
void createHash;
